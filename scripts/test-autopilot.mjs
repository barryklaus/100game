import assert from 'node:assert/strict';
import {build} from 'esbuild';
const load=async path=>{const result=await build({entryPoints:[path],bundle:true,platform:'node',format:'esm',write:false});return import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);};
const {createRoom,joinRoom,applyCommand,advanceCpu,scheduleCpuAction,snapshotForSeat,setConnected}=await load('src/game/hostedCore.ts');
const {LocalSession}=await load('src/game/LocalSession.ts');
const profile=id=>({name:`P${id}`,avatar:id,mood:'Normal'});
for(let count=2;count<=8;count++){
  const room=createRoom(`auto-${count}`,profile(0),'host',0);room.nextRules=true;
  joinRoom(room,profile(1),null,'guest',0);
  applyCommand(room,0,{type:'cpu-count',count:count-2},0);
  applyCommand(room,0,{type:'start'},0);
  room.state.current=room.state.rootTurn=0;room.state.phase='playing';
  const turn=room.state.turn,cards=JSON.stringify(room.state.players.map(p=>p.hand));
  applyCommand(room,0,{type:'autopilot',enabled:true,seat:1},10);
  assert.equal(room.state.players[0].kind,'human');
  assert.equal(room.state.players[0].autopilot,true);
  assert.notEqual(room.state.players[1].autopilot,true,'A forged seat cannot enable someone else');
  assert.equal(room.state.turn,turn);assert.equal(JSON.stringify(room.state.players.map(p=>p.hand)),cards);
  const view=snapshotForSeat(room,1);
  assert.equal(view.state.players[0].autopilot,true);
  assert(view.state.players[0].hand.every(card=>card.id.startsWith('hidden-')),'Autopilot keeps private hands');
  const deadline=room.cpuAction.dueAt;
  applyCommand(room,0,{type:'autopilot',enabled:true},11);
  assert.equal(room.cpuAction.dueAt,deadline,'Repeated enabling cannot restart thinking');
  assert.throws(()=>applyCommand(room,0,{type:'play',cardId:room.state.players[0].hand[0].id,turn},12),/Autopilot off/);
  assert.equal(advanceCpu(room,deadline-1),false);
  assert.equal(advanceCpu(room,deadline),true);
  assert.equal(room.state.turn,turn+1,'Autopilot performs exactly one action per deadline');
  assert.equal(advanceCpu(room,deadline),false);
  if(room.state.phase==='target'){
    assert.throws(()=>applyCommand(room,0,{type:'target',seat:1,turn:room.state.turn},deadline),/Autopilot off/);
    assert.equal(advanceCpu(room,room.cpuAction.dueAt),true);
    assert.equal(room.state.phase,'playing');
    assert.notEqual(room.state.current,0);
  }
  room.state.current=room.state.rootTurn=0;room.state.phase='playing';scheduleCpuAction(room,5000);
  const canceled=room.cpuAction.dueAt;
  applyCommand(room,0,{type:'autopilot',enabled:false},5001);
  assert.equal(room.cpuAction,null);
  assert.equal(advanceCpu(room,canceled+10000),false,'Switching off cancels pending automatic move');
  applyCommand(room,0,{type:'play',cardId:room.state.players[0].hand[0].id,turn:room.state.turn},canceled+10001);
  applyCommand(room,1,{type:'autopilot',enabled:true},canceled+10002);
  setConnected(room,1,false,canceled+10003);
  joinRoom(room,profile(1),'guest','unused',canceled+10004);
  assert.equal(room.state.players[1].autopilot,true,'Reconnect preserves intentional autopilot');
  assert.equal(room.seats[1].autopilot,true);
  const values=new Map(),storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
  const local=new LocalSession(storage);
  local.save({state:room.state,cast:'midnight',practice:null,dismissed:[]});
  assert.equal(local.restore('midnight').state.players[1].autopilot,true,'Local reload preserves autopilot');
  room.state.players[1].autopilot='yes';local.save({state:room.state,cast:'midnight',practice:null,dismissed:[]});
  assert.equal(local.restore('midnight'),null,'Invalid saved toggles rejected');room.state.players[1].autopilot=true;
  room.state.phase='ended';room.state.bust=0;room.state.match.complete=false;
  applyCommand(room,0,{type:'start'},canceled+20000);
  assert.equal(room.state.players[1].autopilot,true,'Auto persists into the next round');
  assert.throws(()=>applyCommand(room,0,{type:'autopilot',enabled:'yes'}),/Autopilot/);
  room.state.match.dead.push(1);
  assert.throws(()=>applyCommand(room,1,{type:'autopilot',enabled:true}),/left this game/);
  if(count>2)assert.throws(()=>applyCommand(room,2,{type:'autopilot',enabled:true}),/active/);
}
const stable=createRoom('stable',profile(0),'host',0);joinRoom(stable,profile(1),null,'guest',0);applyCommand(stable,0,{type:'start'},0);
assert.throws(()=>applyCommand(stable,0,{type:'autopilot',enabled:true}),/100next/);
// A CHOOSE requires its own paced automatic target decision.
const choose=createRoom('choose',profile(0),'host',0);choose.nextRules=true;joinRoom(choose,profile(1),null,'guest',0);applyCommand(choose,0,{type:'start'},0);
choose.state.current=choose.state.rootTurn=0;choose.state.players[0].hand=[{id:'fire-7',suit:'fire',rank:'7'},{id:'water-2',suit:'water',rank:'2'}];
applyCommand(choose,0,{type:'play',cardId:'fire-7',turn:0},1);
applyCommand(choose,0,{type:'autopilot',enabled:true},2);
const due=choose.cpuAction.dueAt;
assert.equal(advanceCpu(choose,due-1),false);assert.equal(advanceCpu(choose,due),true);
assert.equal(choose.state.current,1);assert.equal(choose.state.phase,'playing');assert.equal(choose.state.turn,2);
console.log('Autopilot passed: 2–8 seats, human identity/privacy, own-seat authorization, normal paced play/CHOOSE, no duplicate actions, OFF cancellation, reconnect/reload, rounds, retired seats and stable isolation.');
